package ebpftracer

import (
	"debug/elf"
	"testing"
)

// Prologues of crypto/tls.(*Conn).Write and Read built by Go 1.26: a frame
// larger than the small-frame limit (LEA/SUB first) and a small one.
func TestStackCheckEnd(t *testing.T) {
	for _, tc := range []struct {
		name    string
		machine elf.Machine
		code    []byte
		want    int
	}{
		{"amd64 large frame", elf.EM_X86_64, []byte{0x4c, 0x8d, 0x64, 0x24, 0xb8, 0x4d, 0x3b, 0x66, 0x10, 0x0f, 0x86, 0x93, 0x07, 0x00, 0x00, 0x55, 0x48, 0x89, 0xe5}, 15},
		{"amd64 small frame", elf.EM_X86_64, []byte{0x49, 0x3b, 0x66, 0x10, 0x0f, 0x86, 0x7a, 0x03, 0x00, 0x00, 0x55, 0x48, 0x89, 0xe5}, 10},
		{"arm64 large frame", elf.EM_AARCH64, []byte{0x90, 0x0b, 0x40, 0xf9, 0xf1, 0x43, 0x01, 0xd1, 0x3f, 0x02, 0x10, 0xeb, 0xa9, 0x33, 0x00, 0x54, 0xfe, 0x0f, 0x13, 0xf8}, 16},
		{"arm64 small frame", elf.EM_AARCH64, []byte{0x90, 0x0b, 0x40, 0xf9, 0xff, 0x63, 0x30, 0xeb, 0x09, 0x19, 0x00, 0x54, 0xfe, 0x0f, 0x19, 0xf8}, 12},
		// No stack check (a NOSPLIT function): probe at the entry.
		{"amd64 no check", elf.EM_X86_64, []byte{0x55, 0x48, 0x89, 0xe5, 0xc3}, 0},
		{"arm64 no check", elf.EM_AARCH64, []byte{0xfe, 0x0f, 0x19, 0xf8, 0xc0, 0x03, 0x5f, 0xd6}, 0},
	} {
		if got := stackCheckEnd(tc.machine, tc.code); got != tc.want {
			t.Errorf("%s: stackCheckEnd = %d, want %d", tc.name, got, tc.want)
		}
	}
}
